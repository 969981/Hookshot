"""Open neural rendering's kernels: the checked-in SPIR-V still matches its sources, upstream's sources still take the
portability patches the renderer is built with, and the PTX generators still produce every variant.

The SPIR-V headers (gpu/vk/shaders/opennr_kernels_spv.h, opennr_pre/post_comp_spv.h) are compiled from
third_party/opendlss-nr/shaders and gpu/vk/shaders by scripts/opennr_kernels.py; --check recompiles and compares.
The PTX is generated by nx2/build.py at every build, so a generator that broke would break the build -- this finds it
first, with the generator's own error.

    python -I -B tests/test_opennr_kernels.py --glslang glslangValidator --spirv-val spirv-val
"""
import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import opennr_kernels  # noqa: E402


def fail(text):
    print("FAIL: " + text)
    sys.exit(1)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--glslang", required=True)
    p.add_argument("--spirv-val", required=True)
    a = p.parse_args()

    r = subprocess.run([sys.executable, "-I", "-B", str(ROOT / "scripts" / "opennr_kernels.py"), "--check",
                        "--glslang", a.glslang, "--spirv-val", a.spirv_val],
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    out = r.stdout.decode("utf-8", "replace")
    print(out.strip())
    if r.returncode or "13 kernels and 2 frame passes match" not in out:
        fail("the checked-in SPIR-V headers do not match their sources (python -I -B scripts/opennr_kernels.py)")

    with tempfile.TemporaryDirectory(prefix="opennr-kernels-test-") as tmp:
        # every portability patch applies exactly once (prepare_sources raises otherwise), and changes only what it says
        src = opennr_kernels.prepare_sources(Path(tmp) / "src")
        upstream = opennr_kernels.UPSTREAM / "src"
        changed = sorted(f.name for f in src.iterdir() if f.read_bytes() != (upstream / f.name).read_bytes())
        if changed != sorted({name for name, _, _, _ in opennr_kernels.SOURCE_PATCHES}):
            fail("the prepared copy differs from upstream in %s, the patches name %s" %
                 (changed, sorted({n for n, _, _, _ in opennr_kernels.SOURCE_PATCHES})))
        for name in opennr_kernels.RENDERER_SOURCES:
            if not (src / name).is_file():
                fail("the renderer compiles %s, which upstream no longer has" % name)
        # the PTX: one file per variant upstream's build generates, each a PTX module
        names = opennr_kernels.generate_ptx(Path(tmp) / "ptx")
        if len(names) != len(opennr_kernels.ptx_jobs()) or len(names) < 70:
            fail("%d PTX files for %d variants" % (len(names), len(opennr_kernels.ptx_jobs())))
        for n in names:
            head = (Path(tmp) / "ptx" / n).read_text(encoding="utf-8")[:200]
            if ".version" not in head or ".target" not in head:
                fail("%s is not a PTX module" % n)
        count = opennr_kernels.write_ptx_header(Path(tmp) / "ptx", Path(tmp) / "opennr_ptx.h")
        if count != len(names):
            fail("the embedded header holds %d of %d PTX files" % (count, len(names)))
    print("opennr kernels: SPIR-V checked, %d portability patch(es) apply, %d PTX variants generated" %
          (len(opennr_kernels.SOURCE_PATCHES), len(names)))


if __name__ == "__main__":
    main()
